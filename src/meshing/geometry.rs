//! Deterministic conversion from stable geometry topology to Gmsh `.geo` input.

use super::GmshGeoDocument;
use crate::{
    BodyId, EdgeGeometry, EdgeId, FaceId, GeometryBodyRepresentation, GeometryError,
    GeometryFaceRepresentation, GeometryTopology, MeshDimension, VertexId,
};
use std::collections::{BTreeMap, BTreeSet};

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct GeometryToGmshMap {
    vertex_tags: BTreeMap<VertexId, usize>,
    edge_tags: BTreeMap<EdgeId, usize>,
    pub(super) face_tags: BTreeMap<FaceId, usize>,
    pub(super) face_tag_groups: BTreeMap<FaceId, Vec<usize>>,
    pub(super) body_tags: BTreeMap<BodyId, usize>,
}

impl GeometryToGmshMap {
    pub fn vertex_tag(&self, id: VertexId) -> Option<usize> {
        self.vertex_tags.get(&id).copied()
    }

    pub fn edge_tag(&self, id: EdgeId) -> Option<usize> {
        self.edge_tags.get(&id).copied()
    }

    pub fn face_tag(&self, id: FaceId) -> Option<usize> {
        self.face_tags.get(&id).copied()
    }

    pub fn face_tags(&self, id: FaceId) -> Vec<usize> {
        self.face_tag_groups
            .get(&id)
            .cloned()
            .unwrap_or_else(|| self.face_tag(id).into_iter().collect())
    }

    pub(crate) fn set_face_tags(&mut self, id: FaceId, tags: Vec<usize>) {
        if let Some(&first)=tags.first() { self.face_tags.insert(id,first); }
        self.face_tag_groups.insert(id,tags);
    }

    pub fn body_tag(&self, id: BodyId) -> Option<usize> {
        self.body_tags.get(&id).copied()
    }
}

#[derive(Clone, Debug, PartialEq)]
pub struct GeometryGmshExport {
    pub document: GmshGeoDocument,
    pub map: GeometryToGmshMap,
}

/// Exports stable topology with fresh, deterministic, backend-only Gmsh tags.
pub struct GmshGeometryExporter;

impl GmshGeometryExporter {
    pub fn planar(
        geometry: &GeometryTopology,
        face: FaceId,
        boundary_groups: impl IntoIterator<Item = (impl AsRef<str>, Vec<EdgeId>)>,
        fluid_name: impl AsRef<str>,
    ) -> Result<GeometryGmshExport, GeometryError> {
        geometry.validate()?;
        let face_entity = geometry
            .face(face)
            .ok_or_else(|| missing("face", face.get()))?;
        let GeometryFaceRepresentation::Planar {
            outer_loop,
            inner_loops,
        } = &face_entity.representation
        else {
            return Err(GeometryError::InvalidPrimitive {
                message: "Gmsh planar export requires a planar face".into(),
            });
        };
        validate_name(fluid_name.as_ref())?;
        let boundary_edges = outer_loop
            .iter()
            .chain(inner_loops.iter().flatten())
            .map(|e| e.edge)
            .collect::<BTreeSet<_>>();
        let mut assigned = BTreeMap::new();
        let mut groups = boundary_groups
            .into_iter()
            .map(|(name, edges)| (name.as_ref().to_owned(), edges))
            .collect::<Vec<_>>();
        groups.sort_by(|left, right| left.0.cmp(&right.0));
        for (name, edges) in &groups {
            validate_name(name)?;
            if edges.is_empty() {
                return Err(GeometryError::InvalidPrimitive {
                    message: format!("physical group {name:?} has no edges"),
                });
            }
            for &edge in edges {
                if !boundary_edges.contains(&edge) {
                    return Err(GeometryError::InvalidPrimitive {
                        message: format!(
                            "Group {name:?} contains edge {}, outside the selected fluid face",
                            edge.get()
                        ),
                    });
                }
                if let Some(previous) = assigned.insert(edge, name) {
                    return Err(GeometryError::InvalidPrimitive { message: format!("Edge {} belongs to both {previous:?} and {name:?}; boundary groups must not overlap", edge.get()) });
                }
                if geometry.edge(edge).is_none() || geometry.cad_edge_owner(edge).is_some() {
                    return Err(missing("edge", edge.get()));
                }
            }
        }

        let mut map = GeometryToGmshMap::default();
        for (index, vertex) in geometry
            .vertices()
            .filter(|v| geometry.cad_vertex_owner(v.id).is_none())
            .enumerate()
        {
            map.vertex_tags.insert(vertex.id, 1000 + index);
        }
        for (index, edge) in geometry
            .edges()
            .filter(|e| !matches!(e.geometry, EdgeGeometry::Kernel { .. }))
            .enumerate()
        {
            map.edge_tags.insert(edge.id, 2000 + index);
        }
        map.face_tags.insert(face, 3000);

        let mut source = String::from("// Generated by FLURSYS stable geometry exporter.\n");
        for vertex in geometry
            .vertices()
            .filter(|v| geometry.cad_vertex_owner(v.id).is_none())
        {
            let tag = map.vertex_tag(vertex.id).expect("mapped vertex");
            source.push_str(&format!(
                "Point({tag}) = {{{:.17}, {:.17}, {:.17}}};\n",
                vertex.position.x, vertex.position.y, vertex.position.z
            ));
        }
        for edge in geometry
            .edges()
            .filter(|e| !matches!(e.geometry, EdgeGeometry::Kernel { .. }))
        {
            let tag = map.edge_tag(edge.id).expect("mapped edge");
            match edge.geometry {
                EdgeGeometry::Kernel { .. } => unreachable!("kernel curves use the CAD mesher"),
                EdgeGeometry::Line { start, end } => source.push_str(&format!(
                    "Line({tag}) = {{{}, {}}};\n",
                    map.vertex_tag(start).expect("mapped start"),
                    map.vertex_tag(end).expect("mapped end")
                )),
                EdgeGeometry::CircularArc { start, center, end } => source.push_str(&format!(
                    "Circle({tag}) = {{{}, {}, {}}};\n",
                    map.vertex_tag(start).expect("mapped start"),
                    map.vertex_tag(center).expect("mapped center"),
                    map.vertex_tag(end).expect("mapped end")
                )),
            }
        }
        write_loop(&mut source, 4000, outer_loop, &map)?;
        for (index, loop_edges) in inner_loops.iter().enumerate() {
            write_loop(&mut source, 4001 + index, loop_edges, &map)?;
        }
        let loops = (0..=inner_loops.len())
            .map(|index| (4000 + index).to_string())
            .collect::<Vec<_>>()
            .join(", ");
        source.push_str(&format!("Plane Surface(3000) = {{{loops}}};\n"));
        for (name, edges) in groups {
            let tags = edges
                .into_iter()
                .map(|edge| {
                    map.edge_tag(edge)
                        .expect("validated mapped edge")
                        .to_string()
                })
                .collect::<Vec<_>>()
                .join(", ");
            source.push_str(&format!("Physical Curve(\"{name}\") = {{{tags}}};\n"));
        }
        source.push_str(&format!(
            "Physical Surface(\"{}\") = {{3000}};\n",
            fluid_name.as_ref()
        ));
        Ok(GeometryGmshExport {
            document: GmshGeoDocument::from_source(MeshDimension::TwoD, source),
            map,
        })
    }

    pub fn rectangular_box(
        geometry: &GeometryTopology,
        body: BodyId,
        boundary_groups: impl IntoIterator<Item = (impl AsRef<str>, Vec<FaceId>)>,
        fluid_name: impl AsRef<str>,
    ) -> Result<GeometryGmshExport, GeometryError> {
        let body_entity = geometry
            .body(body)
            .ok_or_else(|| missing("body", body.get()))?;
        let GeometryBodyRepresentation::Box {
            length,
            width,
            height,
        } = body_entity.representation
        else {
            return Err(GeometryError::InvalidPrimitive {
                message: "Gmsh box export requires a box body".into(),
            });
        };
        validate_name(fluid_name.as_ref())?;
        let mut groups = boundary_groups
            .into_iter()
            .map(|(name, faces)| (name.as_ref().to_owned(), faces))
            .collect::<Vec<_>>();
        groups.sort_by(|left, right| left.0.cmp(&right.0));
        let mut map = GeometryToGmshMap::default();
        map.body_tags.insert(body, 7000);
        for (index, &face) in body_entity.faces.iter().enumerate() {
            map.face_tags.insert(face, index + 1);
        }
        for (name, faces) in &groups {
            validate_name(name)?;
            if faces.is_empty() || faces.iter().any(|face| !map.face_tags.contains_key(face)) {
                return Err(GeometryError::InvalidPrimitive {
                    message: format!("physical group {name:?} references invalid box faces"),
                });
            }
        }
        let mut source = String::from(
            "// Generated by FLURSYS stable geometry exporter.\nSetFactory(\"OpenCASCADE\");\n",
        );
        source.push_str(&format!(
            "Box(7000) = {{0, 0, 0, {length:.17}, {width:.17}, {height:.17}}};\n"
        ));
        for (name, faces) in groups {
            let tags = faces
                .into_iter()
                .map(|face| {
                    map.face_tag(face)
                        .expect("validated mapped face")
                        .to_string()
                })
                .collect::<Vec<_>>()
                .join(", ");
            source.push_str(&format!("Physical Surface(\"{name}\") = {{{tags}}};\n"));
        }
        source.push_str(&format!(
            "Physical Volume(\"{}\") = {{7000}};\n",
            fluid_name.as_ref()
        ));
        Ok(GeometryGmshExport {
            document: GmshGeoDocument::from_source(MeshDimension::ThreeD, source),
            map,
        })
    }
    /// Exports a canonical planar-profile extrusion. Generated Gmsh tags stay
    /// backend-local; `out[]` indices are used only to emit physical groups for
    /// stable generated `FaceId` selections.
    pub fn extruded(
        geometry: &GeometryTopology,
        body: BodyId,
        boundary_groups: impl IntoIterator<Item = (impl AsRef<str>, Vec<FaceId>)>,
        fluid_name: impl AsRef<str>,
    ) -> Result<GeometryGmshExport, GeometryError> {
        Self::extruded_with_layers(geometry, body, boundary_groups, fluid_name, None)
    }

    /// Layered surface-to-surface sweep; physical faces use the same stable IDs.
    pub fn extruded_with_layers(
        geometry: &GeometryTopology,
        body: BodyId,
        boundary_groups: impl IntoIterator<Item = (impl AsRef<str>, Vec<FaceId>)>,
        fluid_name: impl AsRef<str>,
        layers: Option<u32>,
    ) -> Result<GeometryGmshExport, GeometryError> {
        if layers.is_some_and(|n| !(1..=10000).contains(&n)) {
            return Err(GeometryError::InvalidPrimitive {message:"Sweep layers must be 1–10000".into()});
        }
        let body_entity = geometry
            .body(body)
            .ok_or_else(|| missing("body", body.get()))?;
        let GeometryBodyRepresentation::Extrude {
            source_face,
            distance,
            top_face,
            side_faces,
            ..
        } = &body_entity.representation
        else {
            return Err(GeometryError::InvalidPrimitive {
                message: "Gmsh extrusion export requires an extrusion body".into(),
            });
        };
        validate_name(fluid_name.as_ref())?;
        let extrusion_vector = planar_face_normal(geometry, *source_face)? * *distance;
        let source_export = Self::planar(
            geometry,
            *source_face,
            Vec::<(String, Vec<EdgeId>)>::new(),
            "__profile",
        )?;
        let mut source = source_export.document.to_geo_string().map_err(|error| {
            GeometryError::InvalidPrimitive {
                message: error.to_string(),
            }
        })?;
        source = source.replace("Physical Surface(\"__profile\") = {3000};\n", "");
        let sweep = layers.map(|n|format!("Layers {{{n}}}; Recombine;")).unwrap_or_default();
        source.push_str(&format!(
            "out[] = Extrude {{{:.17}, {:.17}, {:.17}}} {{ Surface{{3000}}; {sweep} }};\n",
            extrusion_vector.x, extrusion_vector.y, extrusion_vector.z
        ));
        let mut groups = boundary_groups
            .into_iter()
            .map(|(name, faces)| (name.as_ref().to_owned(), faces))
            .collect::<Vec<_>>();
        groups.sort_by(|left, right| left.0.cmp(&right.0));
        let mut assigned = std::collections::BTreeSet::new();
        for (name, faces) in &groups {
            for face in faces {
                if !assigned.insert(*face) {
                    return Err(GeometryError::InvalidPrimitive { message: format!("Extrusion boundary face {} is assigned more than once (group {name:?})", face.get()) });
                }
            }
        }
        if body_entity
            .faces
            .iter()
            .any(|face| !assigned.contains(face))
        {
            return Err(GeometryError::InvalidPrimitive { message: "Assign every extrusion boundary face to exactly one physical group before meshing".into() });
        }
        for (name, faces) in groups {
            validate_name(&name)?;
            if faces.is_empty() || faces.iter().any(|face| !body_entity.faces.contains(face)) {
                return Err(GeometryError::InvalidPrimitive {
                    message: format!("physical group {name:?} references invalid extrusion faces"),
                });
            }
            let expressions = faces
                .iter()
                .map(|face| {
                    if face == source_face {
                        Ok("3000".to_string())
                    } else if face == top_face {
                        Ok("out[0]".to_string())
                    } else {
                        side_faces
                            .iter()
                            .position(|candidate| candidate == face)
                            .map(|index| format!("out[{}]", index + 2))
                            .ok_or_else(|| GeometryError::InvalidPrimitive {
                                message: format!(
                                    "face {} is not an extrusion boundary",
                                    face.get()
                                ),
                            })
                    }
                })
                .collect::<Result<Vec<_>, GeometryError>>()?
                .join(", ");
            source.push_str(&format!(
                "Physical Surface(\"{name}\") = {{{expressions}}};\n"
            ));
        }
        source.push_str(&format!(
            "Physical Volume(\"{}\") = {{out[1]}};\n",
            fluid_name.as_ref()
        ));
        Ok(GeometryGmshExport {
            document: GmshGeoDocument::from_source(MeshDimension::ThreeD, source),
            map: source_export.map,
        })
    }
}

fn planar_face_normal(
    geometry: &GeometryTopology,
    face: FaceId,
) -> Result<crate::Vec3, GeometryError> {
    let GeometryFaceRepresentation::Planar { outer_loop, .. } = &geometry
        .face(face)
        .ok_or_else(|| missing("face", face.get()))?
        .representation
    else {
        return Err(GeometryError::InvalidPrimitive {
            message: "extrusion source must be planar".into(),
        });
    };
    let points = outer_loop
        .iter()
        .map(|oriented| {
            let edge = geometry
                .edge(oriented.edge)
                .ok_or_else(|| missing("edge", oriented.edge.get()))?;
            let (start, end) = match edge.geometry {
                EdgeGeometry::Line { start, end }
                | EdgeGeometry::CircularArc { start, end, .. }
                | EdgeGeometry::Kernel { start, end, .. } => (start, end),
            };
            let vertex = if oriented.reversed { end } else { start };
            geometry
                .vertex(vertex)
                .map(|vertex| vertex.position)
                .ok_or_else(|| missing("vertex", vertex.get()))
        })
        .collect::<Result<Vec<_>, GeometryError>>()?;
    let origin = points
        .first()
        .copied()
        .ok_or_else(|| GeometryError::InvalidPrimitive {
            message: "extrusion source has no boundary points".into(),
        })?;
    for index in 1..points.len().saturating_sub(1) {
        if let Some(normal) = (points[index] - origin)
            .cross(points[index + 1] - origin)
            .normalized()
        {
            return Ok(normal);
        }
    }
    Err(GeometryError::InvalidPrimitive {
        message: "extrusion source has no finite plane normal".into(),
    })
}

fn write_loop(
    source: &mut String,
    tag: usize,
    edges: &[crate::OrientedEdge],
    map: &GeometryToGmshMap,
) -> Result<(), GeometryError> {
    let tags = edges
        .iter()
        .map(|oriented| {
            let tag = map
                .edge_tag(oriented.edge)
                .ok_or_else(|| missing("edge", oriented.edge.get()))?;
            Ok(if oriented.reversed {
                format!("-{tag}")
            } else {
                tag.to_string()
            })
        })
        .collect::<Result<Vec<_>, GeometryError>>()?
        .join(", ");
    source.push_str(&format!("Curve Loop({tag}) = {{{tags}}};\n"));
    Ok(())
}

fn validate_name(name: &str) -> Result<(), GeometryError> {
    if name.is_empty()
        || name
            .chars()
            .any(|character| character == '"' || character.is_control())
    {
        return Err(GeometryError::InvalidPrimitive {
            message: format!("invalid Gmsh physical name {name:?}"),
        });
    }
    Ok(())
}

fn missing(entity: &'static str, id: u64) -> GeometryError {
    GeometryError::EntityNotFound { entity, id }
}
